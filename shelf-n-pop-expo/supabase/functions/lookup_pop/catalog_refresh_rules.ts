function nullableFiniteNumber(value: unknown): number | null {
  if (value == null || value === "") return null;
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

export function resolveLookupEstimatedValues(
  existingCatalogValue: unknown,
  parsedCatalogValue: unknown,
  requestedVariantValue: unknown,
): { catalogEstimatedValue: number | null; lookupEstimatedValue: number | null } {
  const existingValue = nullableFiniteNumber(existingCatalogValue);
  const parsedValue = nullableFiniteNumber(parsedCatalogValue);
  const variantValue = nullableFiniteNumber(requestedVariantValue);
  const catalogEstimatedValue = variantValue != null ? (existingValue ?? parsedValue) : (parsedValue ?? existingValue);

  return {
    catalogEstimatedValue,
    lookupEstimatedValue: variantValue ?? catalogEstimatedValue,
  };
}

