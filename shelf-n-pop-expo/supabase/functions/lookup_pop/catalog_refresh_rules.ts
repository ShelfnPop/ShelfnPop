export function shouldPromoteSpecificSet(existingSetName: unknown, parsedSetName: unknown): boolean {
  const existing = normalizeSetName(existingSetName);
  const parsed = normalizeSetName(parsedSetName);

  if (!parsed) return false;
  if (!existing) return true;
  return GENERIC_SET_NAMES.has(existing) && parsed !== existing;
}

